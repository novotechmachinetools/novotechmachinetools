def target(name):
    for rx, t in RULES:
        if re.search(rx, name, re.I):
            return t, rx
    return "/brochures", None


def main():
    ht = open(HT, encoding="utf-8").read()
    head, _, rest = ht.partition(BEGIN)
    if _:
        _, _, tail = rest.partition(END)
        tail = tail.lstrip("\n")
    else:  # first run: insert before the compression section
        cut = ht.index("# ---- Compression")
        head, tail = ht[:cut], ht[cut:]
    manual = set(re.findall(r'^Redirect 301 "/(files/[^"]+)"', head + tail, re.M))
    lines, fallback = [], []
    for f in (l.strip() for l in open(LIST, encoding="utf-8")):
        if not f or f in manual:
            continue
        name = f.split("/", 1)[1]
        t, rx = target(name)
        if rx is None:
            fallback.append(name)
        lines.append(f'Redirect 301 "/{f}" "{t}"')
    block = BEGIN + "\n" + "\n".join(lines) + "\n" + END + "\n\n"
    open(HT, "w", encoding="utf-8").write(head.rstrip("\n") + "\n\n" + block + tail)
    print(f"{len(lines)} generated redirects ({len(manual)} hand-written kept); fallback to /brochures: {len(fallback)}")
    for n in fallback:
        print("  ", n)


if __name__ == "__main__":
    main()
